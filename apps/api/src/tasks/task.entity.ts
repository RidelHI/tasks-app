import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Index,
  PrimaryColumn,
  UpdateDateColumn,
} from 'typeorm';
import { DEFAULT_TASK_STATUS, TASK_STATUSES, type TaskStatus } from './task-status.js';
import {
  TASK_ASSIGNEE_MAX_LENGTH,
  TASK_DESCRIPTION_MAX_LENGTH,
  TASK_TITLE_MAX_LENGTH,
} from './task.constants.js';

const STATUS_VALUES = TASK_STATUSES.map((status) => `'${status}'`).join(', ');

/**
 * The indexes serve the list queries: each one matches a filter and the order (newest first),
 * so a page is read in index order without sorting. PostgreSQL scans them backwards for DESC.
 */
@Entity('tasks')
@Check('CHK_tasks_status', `"status" IN (${STATUS_VALUES})`)
@Index('IDX_tasks_created_at', ['createdAt', 'id'])
@Index('IDX_tasks_status_created_at', ['status', 'createdAt', 'id'])
// On `lower(assignee)`, which a decorator cannot express: written by hand in the migration and
// declared here so the schema sync leaves it alone.
@Index('IDX_tasks_assignee_created_at', { synchronize: false })
export class Task {
  /** UUIDv7 generated by PostgreSQL 18: unique like v4, but time-ordered (index friendly). */
  @PrimaryColumn({ type: 'uuid', default: () => 'uuidv7()', primaryKeyConstraintName: 'PK_tasks' })
  id: string;

  @Column({ type: 'varchar', length: TASK_TITLE_MAX_LENGTH })
  title: string;

  @Column({ type: 'varchar', length: TASK_DESCRIPTION_MAX_LENGTH, nullable: true })
  description: string | null;

  @Column({ type: 'varchar', length: 20, default: DEFAULT_TASK_STATUS })
  status: TaskStatus;

  /** Free-text name of the person responsible (no user accounts yet). */
  @Column({ type: 'varchar', length: TASK_ASSIGNEE_MAX_LENGTH, nullable: true })
  assignee: string | null;

  /** Calendar date without time zone; the pg driver returns it as `YYYY-MM-DD`. */
  @Column({ type: 'date', nullable: true })
  dueDate: string | null;

  @CreateDateColumn({ type: 'timestamptz' })
  createdAt: Date;

  @UpdateDateColumn({ type: 'timestamptz' })
  updatedAt: Date;
}
